const PREMIUM_PREFIXES = ['The Grand Royal', 'Signature Reserve', 'Platinum Collection'];

export function getHotels(destId) {
  return HOTELS[destId] || HOTELS.japan;
}

export function getPremiumHotels(destId) {
  const base = getHotels(destId);
  return base.map((h, i) => ({
    ...h,
    name: `${PREMIUM_PREFIXES[i % PREMIUM_PREFIXES.length]} - ${h.name}`,
    price: Math.round(h.price * 1.65),
    originalPrice: Math.round(h.price * 2.1),
    rating: Math.min(9.9, +(h.rating + 0.2).toFixed(1)),
    ratingLabel: 'Exceptional',
    desc: `VIP Platinum Upgrade: ${h.desc}`,
    vipAccess: true,
  }));
}

export function getBudgetHotels(destId) {
  const base = getHotels(destId);
  return base.map((h) => ({
    ...h,
    name: `${h.name} (Saver Stay)`,
    price: Math.max(3500, Math.round(h.price * 0.6)),
    originalPrice: h.price,
    rating: Math.max(8.5, +(h.rating - 0.4).toFixed(1)),
    ratingLabel: 'Very Good',
    desc: `Budget-friendly option: ${h.desc}`,
    vipAccess: false,
  }));
}
